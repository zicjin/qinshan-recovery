emcProjScheme.copySharePage = {
    getBtnToolbar : function() {
        var _this = this;
        return {
            type : 'btnToolbar',
            items : [ {
                type : 'button',
                text : 'GIKAM.BUTTON.CONFIRM',
                icon : 'select',
                onClick : function() {
                    var formData = Gikam.getComp('emc-copy-share-form').getData();
                    if (Gikam.isEmpty(formData.copyShare)) {
                        Gikam.alert('EMC.MODULE.BP.PROJECT.PROJSCHEMES.TIP.RIGHT_NUMBER');
                        return;
                    }
                    Gikam.getLastModal().close(formData);
                }
            }, {
                type : 'button',
                text : 'GIKAM.BUTTON.BACK',
                icon : 'back',
                onClick : function() {
                    Gikam.getLastModal().close();
                }
            } ]
        }
    },

    getBaseInfoForm : function() {
        var _this = this;
        return {
            type : 'form',
            id : 'emc-copy-share-form',
            titleWidth : 60,
            fields : emcProjScheme.getCopyShareInfoFormFields(),
            columns : 1
        };

    },

    createPage : function() {
        Gikam.create('layout', {
            center : {
                items : [ this.getBtnToolbar(), this.getBaseInfoForm() ]
            },
            renderTo : Gikam.getLastModal().window.$dom,
        });
        return this;
    },

    init : function(param) {
        this.param = param;
        this.createPage();
    },

}
