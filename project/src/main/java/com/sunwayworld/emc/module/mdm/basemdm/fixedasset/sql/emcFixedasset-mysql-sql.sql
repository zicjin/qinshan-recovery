CREATE TABLE IF NOT EXISTS `T_EMC_FIXEDASSET`(
    `ID` BIGINT(32)  NOT NULL COMMENT '主键',
     `CREATEDBYID` VARCHAR(32)  DEFAULT NULL COMMENT '制单人编码',
     `CREATEDBYNAME` VARCHAR(64)  DEFAULT NULL COMMENT '制单人名称',
     `CREATEDTIME` DATETIME  DEFAULT NULL COMMENT '制单时间',
     `CREATEDBYORGID` VARCHAR(32)  DEFAULT NULL COMMENT '制单人单位编码',
     `CREATEDBYORGNAME` VARCHAR(256)  DEFAULT NULL COMMENT '制单人单位名称',
     `ASSETCATEGORY` VARCHAR(36)  DEFAULT NULL COMMENT '资产类型',
     `ASSETNAME` VARCHAR(36)  DEFAULT NULL COMMENT '资产名称',
     `MODEL` VARCHAR(36)  DEFAULT NULL COMMENT '型号',
     `QUANTITY` bigint(15)  DEFAULT NULL COMMENT '数量',
     `PRICE` double(15,4)  DEFAULT NULL COMMENT '单价金额',
     `TOTALAMOUNT` double(15,4)  DEFAULT NULL COMMENT '总价金额',
     `PURCHASETIME` DATETIME  DEFAULT NULL COMMENT '购入时间',
     `FACTORYNO` VARCHAR(36)  DEFAULT NULL COMMENT '出厂编号',
     `RESPONSITYORGID` VARCHAR(36)  DEFAULT NULL COMMENT '责任科室Id',
     `USEORGID` VARCHAR(36)  DEFAULT NULL COMMENT '使用科室Id',
     `USEMODIFY` VARCHAR(36)  DEFAULT NULL COMMENT '使用变更',
     `STOREPLACE` VARCHAR(36)  DEFAULT NULL COMMENT '存放地点',
     `REMARK` VARCHAR(540)  DEFAULT NULL COMMENT '备注',
 PRIMARY KEY (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='固定资产管理表';


