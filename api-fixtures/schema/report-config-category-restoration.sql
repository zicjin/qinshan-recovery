-- Add the historical stock 14.1.5 report CATEGORY compatibility column only.
-- Production metadata captured 2026-11-09 also lacks CATEGORY: this is not a
-- production-import repair or an assertion of current production equivalence.
-- Source: project/sql/核心发版14.1.5/init-sql/oracle/0.common_sql_oracle-1.txt:2321-2334.
-- Oracle DDL implicitly commits: this is not an atomic transaction rollback.
-- Use a dedicated session with no pending writes. Preserve partial-failure logs;
-- inspect any partially added column before retrying. Do not backfill categories.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
WHENEVER OSERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON
SET SERVEROUTPUT ON
DECLARE
  n PLS_INTEGER;
  category_count PLS_INTEGER;
  rows_before NUMBER;
  rows_after NUMBER;
  PROCEDURE verify_columns(with_category BOOLEAN) IS
    expected_count PLS_INTEGER := 7;
  BEGIN
    IF with_category THEN expected_count := 8; END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG';
    IF n<>expected_count THEN RAISE_APPLICATION_ERROR(-20002, 'Unexpected report config column count'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=1 AND COLUMN_NAME='ID' AND DATA_TYPE='VARCHAR2'
      AND DATA_LENGTH=128 AND CHAR_LENGTH=128 AND CHAR_USED='B' AND NULLABLE='N'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config ID'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=2 AND COLUMN_NAME='VERSION' AND DATA_TYPE='NUMBER'
      AND DATA_LENGTH=22 AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config VERSION'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=3 AND COLUMN_NAME='ORDERNO' AND DATA_TYPE='NUMBER'
      AND DATA_LENGTH=22 AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config ORDERNO'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=4 AND COLUMN_NAME='REMARK' AND DATA_TYPE='CLOB'
      AND DATA_LENGTH=4000 AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config REMARK'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=5 AND COLUMN_NAME='NAME' AND DATA_TYPE='CLOB'
      AND DATA_LENGTH=4000 AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config NAME'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=6 AND COLUMN_NAME='CREATEDBYORGNAME' AND DATA_TYPE='VARCHAR2'
      AND DATA_LENGTH=270 AND CHAR_LENGTH=270 AND CHAR_USED='B' AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report config CREATEDBYORGNAME'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
      WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
      AND COLUMN_ID=7 AND COLUMN_NAME='REPORTCONFIGCATEGORY' AND DATA_TYPE='VARCHAR2'
      AND DATA_LENGTH=120 AND CHAR_LENGTH=120 AND CHAR_USED='B' AND NULLABLE='Y'
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible project report classification'); END IF;
    IF with_category THEN
      SELECT COUNT(*) INTO n FROM ALL_TAB_COLS
        WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
        AND COLUMN_ID=8 AND COLUMN_NAME='CATEGORY' AND DATA_TYPE='VARCHAR2'
        AND DATA_LENGTH=36 AND CHAR_LENGTH=36 AND CHAR_USED='B' AND NULLABLE='Y'
        AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND DEFAULT_LENGTH IS NULL
        AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO';
      IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Incompatible report CATEGORY'); END IF;
      SELECT COUNT(*) INTO n FROM ALL_COL_COMMENTS
        WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
        AND COLUMN_NAME='CATEGORY' AND COMMENTS='类别';
      IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Partial or incompatible report CATEGORY comment'); END IF;
      SELECT COUNT(*) INTO n FROM ALL_CONS_COLUMNS
        WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
        AND COLUMN_NAME='CATEGORY';
      IF n<>0 THEN RAISE_APPLICATION_ERROR(-20002, 'Unexpected report CATEGORY constraint'); END IF;
    END IF;
  END;
BEGIN
  IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'LIMS_RUNTIME_LOCAL'
     OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1'
     OR SYS_CONTEXT('USERENV', 'SESSION_USER') NOT IN ('SYS', 'LIMS_RUNTIME_LOCAL') THEN
    RAISE_APPLICATION_ERROR(-20001, 'Report CATEGORY fixture requires the authorized local runtime session');
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG'
    AND TEMPORARY='N' AND NESTED='NO' AND SECONDARY='N' AND PARTITIONED='NO';
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20002, 'Missing or incompatible report config table'); END IF;
  SELECT COUNT(*) INTO category_count FROM ALL_TAB_COLS
    WHERE OWNER='LIMS_RUNTIME_LOCAL' AND TABLE_NAME='T_CORE_REPORT_CONFIG' AND COLUMN_NAME='CATEGORY';
  IF category_count=1 THEN
    verify_columns(TRUE);
    DBMS_OUTPUT.PUT_LINE('Report CATEGORY already equivalent; no DDL executed');
    RETURN;
  ELSIF category_count<>0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Ambiguous report CATEGORY metadata');
  END IF;
  verify_columns(FALSE);
  SELECT COUNT(*) INTO rows_before FROM "LIMS_RUNTIME_LOCAL"."T_CORE_REPORT_CONFIG";
  -- All target metadata is checked before the first implicitly committing DDL.
  EXECUTE IMMEDIATE 'ALTER TABLE "LIMS_RUNTIME_LOCAL"."T_CORE_REPORT_CONFIG" ADD ("CATEGORY" VARCHAR2(36 BYTE))';
  EXECUTE IMMEDIATE 'COMMENT ON COLUMN "LIMS_RUNTIME_LOCAL"."T_CORE_REPORT_CONFIG"."CATEGORY" IS ''类别''';
  verify_columns(TRUE);
  SELECT COUNT(*) INTO rows_after FROM "LIMS_RUNTIME_LOCAL"."T_CORE_REPORT_CONFIG";
  IF rows_after<>rows_before THEN RAISE_APPLICATION_ERROR(-20003, 'Report config row count changed'); END IF;
  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM "LIMS_RUNTIME_LOCAL"."T_CORE_REPORT_CONFIG" WHERE "CATEGORY" IS NOT NULL' INTO n;
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20003, 'New report CATEGORY must remain NULL'); END IF;
  DBMS_OUTPUT.PUT_LINE('Nullable report CATEGORY restored; business category values unchanged');
END;
