-- Narrow production-derived alignment for the original local logical clone.
-- Oracle DDL commits implicitly. Keep application/schema writers idle and retain logs.
-- Preserve existing rows, including duplicate FOLDERNO values, with ENABLE NOVALIDATE.
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON
SET SERVEROUTPUT ON
ALTER SESSION SET DDL_LOCK_TIMEOUT=5;
DECLARE
  n NUMBER;
  index_count NUMBER;
  existing_count NUMBER;
  rows_before NUMBER;
  duplicate_groups_before NUMBER;

  PROCEDURE assert_index IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_INDEXES
      WHERE INDEX_NAME='IDX_T_LIMS_FOLDERS_FOLDERNO' AND TABLE_OWNER=USER
        AND TABLE_NAME='T_LIMS_FOLDERS'
        AND INDEX_TYPE='NORMAL' AND UNIQUENESS='NONUNIQUE' AND STATUS='VALID'
        AND PARTITIONED='NO' AND TEMPORARY='N';
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20220,'Folder index definition conflicts'); END IF;
    SELECT COUNT(*) INTO n FROM USER_IND_COLUMNS
      WHERE INDEX_NAME='IDX_T_LIMS_FOLDERS_FOLDERNO';
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20220,'Folder index column count conflicts'); END IF;
    SELECT COUNT(*) INTO n FROM USER_IND_COLUMNS
      WHERE INDEX_NAME='IDX_T_LIMS_FOLDERS_FOLDERNO' AND TABLE_NAME='T_LIMS_FOLDERS'
        AND COLUMN_NAME='FOLDERNO' AND COLUMN_POSITION=1 AND DESCEND='ASC';
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20220,'Folder index column conflicts'); END IF;
  END;

  PROCEDURE assert_constraint IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
      WHERE CONSTRAINT_NAME='UKT_LIMS_FOLDERS_FOLDERNO' AND TABLE_NAME='T_LIMS_FOLDERS'
        AND CONSTRAINT_TYPE='U' AND STATUS='ENABLED' AND VALIDATED='NOT VALIDATED'
        AND DEFERRABLE='NOT DEFERRABLE' AND DEFERRED='IMMEDIATE'
        AND INDEX_OWNER=USER AND INDEX_NAME='IDX_T_LIMS_FOLDERS_FOLDERNO'
        AND GENERATED='USER NAME' AND RELY IS NULL AND BAD IS NULL
        AND INVALID IS NULL AND VIEW_RELATED IS NULL;
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20221,'Folder unique constraint definition conflicts'); END IF;
    SELECT COUNT(*) INTO n FROM USER_CONS_COLUMNS
      WHERE CONSTRAINT_NAME='UKT_LIMS_FOLDERS_FOLDERNO';
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20221,'Folder unique constraint column count conflicts'); END IF;
    SELECT COUNT(*) INTO n FROM USER_CONS_COLUMNS
      WHERE CONSTRAINT_NAME='UKT_LIMS_FOLDERS_FOLDERNO' AND TABLE_NAME='T_LIMS_FOLDERS'
        AND COLUMN_NAME='FOLDERNO' AND POSITION=1;
    IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20221,'Folder unique constraint column conflicts'); END IF;
  END;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'LIMS_RUNTIME_LOCAL'
      OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'LIMS_RUNTIME_LOCAL'
      OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20222,'Wrong local alignment target');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES
    WHERE TABLE_NAME='T_LIMS_FOLDERS' AND TEMPORARY='N' AND NESTED='NO'
      AND SECONDARY='N' AND PARTITIONED='NO' AND IOT_TYPE IS NULL AND READ_ONLY='NO';
  IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20223,'Folder table precondition conflicts'); END IF;
  SELECT COUNT(*) INTO n FROM USER_TAB_COLS
    WHERE TABLE_NAME='T_LIMS_FOLDERS' AND COLUMN_NAME='FOLDERNO'
      AND COLUMN_ID=9 AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=30
      AND DATA_PRECISION IS NULL AND DATA_SCALE IS NULL AND NULLABLE='N'
      AND CHAR_USED='B' AND CHAR_LENGTH=30 AND DEFAULT_LENGTH IS NULL
      AND HIDDEN_COLUMN='NO' AND VIRTUAL_COLUMN='NO' AND USER_GENERATED='YES'
      AND IDENTITY_COLUMN='NO' AND DEFAULT_ON_NULL='NO' AND DATA_TYPE_OWNER IS NULL;
  IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20223,'Folder column precondition conflicts'); END IF;

  -- Finish all known conflict checks before either implicitly committing DDL.
  SELECT COUNT(*) INTO index_count FROM USER_INDEXES
    WHERE INDEX_NAME='IDX_T_LIMS_FOLDERS_FOLDERNO';
  IF index_count > 1 THEN RAISE_APPLICATION_ERROR(-20220,'Folder index identity conflicts'); END IF;
  IF index_count = 1 THEN assert_index; END IF;
  SELECT COUNT(*) INTO existing_count FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME='UKT_LIMS_FOLDERS_FOLDERNO';
  IF existing_count > 1 THEN RAISE_APPLICATION_ERROR(-20221,'Folder constraint identity conflicts'); END IF;
  IF existing_count = 0 THEN
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS c
      WHERE c.TABLE_NAME='T_LIMS_FOLDERS' AND c.CONSTRAINT_TYPE='U'
        AND EXISTS (SELECT 1 FROM USER_CONS_COLUMNS cc
                    WHERE cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME AND cc.COLUMN_NAME='FOLDERNO')
        AND (SELECT COUNT(*) FROM USER_CONS_COLUMNS cc WHERE cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME)=1;
    IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20221,'Another folder unique constraint already exists'); END IF;
  ELSE
    assert_constraint;
    IF index_count <> 1 THEN RAISE_APPLICATION_ERROR(-20220,'Folder unique constraint index is missing'); END IF;
  END IF;
  SELECT COUNT(*) INTO rows_before FROM T_LIMS_FOLDERS;
  SELECT COUNT(*) INTO duplicate_groups_before
    FROM (SELECT FOLDERNO FROM T_LIMS_FOLDERS GROUP BY FOLDERNO HAVING COUNT(*)>1);

  IF index_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX "IDX_T_LIMS_FOLDERS_FOLDERNO" ON "T_LIMS_FOLDERS" ("FOLDERNO")';
  END IF;
  IF existing_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE "T_LIMS_FOLDERS" ADD CONSTRAINT "UKT_LIMS_FOLDERS_FOLDERNO" UNIQUE ("FOLDERNO") USING INDEX "IDX_T_LIMS_FOLDERS_FOLDERNO" ENABLE NOVALIDATE';
  END IF;
  assert_index;
  assert_constraint;
  SELECT COUNT(*) INTO n FROM T_LIMS_FOLDERS;
  IF n <> rows_before THEN RAISE_APPLICATION_ERROR(-20224,'Folder row count changed during alignment'); END IF;
  SELECT COUNT(*) INTO n
    FROM (SELECT FOLDERNO FROM T_LIMS_FOLDERS GROUP BY FOLDERNO HAVING COUNT(*)>1);
  IF n <> duplicate_groups_before THEN RAISE_APPLICATION_ERROR(-20224,'Folder duplicate groups changed during alignment'); END IF;
  DBMS_OUTPUT.PUT_LINE('Folder constraint aligned; existing duplicate groups preserved: '||duplicate_groups_before);
END;
