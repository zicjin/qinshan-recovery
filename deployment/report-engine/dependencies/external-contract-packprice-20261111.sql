-- Current-production dictionary-derived logical clone for the contract summary.
-- Run as the isolated application's schema owner. No DB link or business rows.
-- Oracle DDL commits implicitly; a failed create is not transaction rollback.
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON
SET SERVEROUTPUT ON
ALTER SESSION SET DDL_LOCK_TIMEOUT=5;
DECLARE
  n NUMBER;
  existing_table NUMBER;
  PROCEDURE verify_definition IS
    actual_columns NUMBER;
    expected_columns NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES
      WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE' AND TEMPORARY='N'
        AND SECONDARY='N' AND NESTED='NO' AND PARTITIONED='NO'
        AND IOT_TYPE IS NULL AND CLUSTER_NAME IS NULL AND READ_ONLY='NO';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20271,'Packprice table semantics differ'); END IF;
    SELECT COUNT(*) INTO actual_columns FROM USER_TAB_COLUMNS WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE';
    SELECT COUNT(*) INTO expected_columns FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE' AND DEFAULT_LENGTH IS NULL AND (
       (COLUMN_ID=1 AND COLUMN_NAME='ID' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=32 AND CHAR_USED='B' AND NULLABLE='N') OR
       (COLUMN_ID=2 AND COLUMN_NAME='CONTRACTID' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=32 AND CHAR_USED='B' AND NULLABLE='Y') OR
       (COLUMN_ID=3 AND COLUMN_NAME='PROJECTNAME' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=320 AND CHAR_USED='B' AND NULLABLE='Y') OR
       (COLUMN_ID=4 AND COLUMN_NAME='PACKINFO' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=320 AND CHAR_USED='B' AND NULLABLE='Y') OR
       (COLUMN_ID=5 AND COLUMN_NAME='AMOUNT' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=18 AND DATA_SCALE=2 AND NULLABLE='Y') OR
       (COLUMN_ID=6 AND COLUMN_NAME='OPERATOR' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=300 AND CHAR_USED='B' AND NULLABLE='Y') OR
       (COLUMN_ID=7 AND COLUMN_NAME='OPERATETIME' AND DATA_TYPE='DATE' AND NULLABLE='Y') OR
       (COLUMN_ID=8 AND COLUMN_NAME='REMARK' AND DATA_TYPE='VARCHAR2' AND DATA_LENGTH=300 AND CHAR_USED='B' AND NULLABLE='Y') OR
       (COLUMN_ID=9 AND COLUMN_NAME='REALAMOUNT' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=18 AND DATA_SCALE=2 AND NULLABLE='Y'));
    IF actual_columns<>9 OR expected_columns<>9 THEN RAISE_APPLICATION_ERROR(-20272,'Packprice columns differ'); END IF;
    SELECT COUNT(*) INTO n FROM USER_INDEXES
      WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE' AND INDEX_NAME='PK_CRM_CONTRACT_PACKPRICE'
        AND INDEX_TYPE='NORMAL' AND UNIQUENESS='UNIQUE' AND STATUS='VALID';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20273,'Packprice primary index differs'); END IF;
    SELECT COUNT(*) INTO n FROM USER_IND_COLUMNS WHERE INDEX_NAME='PK_CRM_CONTRACT_PACKPRICE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20273,'Packprice primary index column count differs'); END IF;
    SELECT COUNT(*) INTO n FROM USER_IND_COLUMNS
      WHERE INDEX_NAME='PK_CRM_CONTRACT_PACKPRICE' AND TABLE_NAME='T_CRM_CONTRACT_PACKPRICE'
        AND COLUMN_NAME='ID' AND COLUMN_POSITION=1 AND DESCEND='ASC';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20273,'Packprice primary index columns differ'); END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
      WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE' AND CONSTRAINT_NAME='PK_CRM_CONTRACT_PACKPRICE'
        AND CONSTRAINT_TYPE='P' AND STATUS='ENABLED' AND VALIDATED='VALIDATED'
        AND DEFERRABLE='NOT DEFERRABLE' AND DEFERRED='IMMEDIATE'
        AND INDEX_OWNER=USER AND INDEX_NAME='PK_CRM_CONTRACT_PACKPRICE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20274,'Packprice primary constraint differs'); END IF;
    SELECT COUNT(*) INTO n FROM USER_CONS_COLUMNS
      WHERE CONSTRAINT_NAME='PK_CRM_CONTRACT_PACKPRICE' AND TABLE_NAME='T_CRM_CONTRACT_PACKPRICE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20274,'Packprice primary constraint column count differs'); END IF;
    SELECT COUNT(*) INTO n FROM USER_CONS_COLUMNS
      WHERE CONSTRAINT_NAME='PK_CRM_CONTRACT_PACKPRICE' AND TABLE_NAME='T_CRM_CONTRACT_PACKPRICE'
        AND COLUMN_NAME='ID' AND POSITION=1;
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20274,'Packprice primary constraint columns differ'); END IF;
    SELECT COUNT(*) INTO n FROM USER_TRIGGERS WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE';
    IF n<>0 THEN RAISE_APPLICATION_ERROR(-20275,'Unexpected packprice trigger'); END IF;
  END;
BEGIN
  IF USER IN ('SYS','SYSTEM') OR SYS_CONTEXT('USERENV','SESSION_USER')<>SYS_CONTEXT('USERENV','CURRENT_SCHEMA') THEN
    RAISE_APPLICATION_ERROR(-20270,'Isolated application schema owner required');
  END IF;
  SELECT COUNT(*) INTO existing_table FROM USER_TABLES WHERE TABLE_NAME='T_CRM_CONTRACT_PACKPRICE';
  IF existing_table=1 THEN
    verify_definition;
    DBMS_OUTPUT.PUT_LINE('Existing packprice definition verified; rows unchanged');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS
    WHERE OBJECT_NAME IN ('T_CRM_CONTRACT_PACKPRICE','PK_CRM_CONTRACT_PACKPRICE');
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20276,'Packprice object name collision'); END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='PK_CRM_CONTRACT_PACKPRICE';
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20276,'Packprice constraint name collision'); END IF;
  EXECUTE IMMEDIATE 'CREATE TABLE "T_CRM_CONTRACT_PACKPRICE" (
    "ID" VARCHAR2(32 BYTE) NOT NULL,
    "CONTRACTID" VARCHAR2(32 BYTE),
    "PROJECTNAME" VARCHAR2(320 BYTE),
    "PACKINFO" VARCHAR2(320 BYTE),
    "AMOUNT" NUMBER(18,2),
    "OPERATOR" VARCHAR2(300 BYTE),
    "OPERATETIME" DATE,
    "REMARK" VARCHAR2(300 BYTE),
    "REALAMOUNT" NUMBER(18,2)
  )';
  EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX "PK_CRM_CONTRACT_PACKPRICE" ON "T_CRM_CONTRACT_PACKPRICE" ("ID")';
  EXECUTE IMMEDIATE 'ALTER TABLE "T_CRM_CONTRACT_PACKPRICE" ADD CONSTRAINT "PK_CRM_CONTRACT_PACKPRICE" PRIMARY KEY ("ID") USING INDEX "PK_CRM_CONTRACT_PACKPRICE" ENABLE VALIDATE';
  verify_definition;
  DBMS_OUTPUT.PUT_LINE('Packprice logical structure installed; no business rows inserted');
END;
