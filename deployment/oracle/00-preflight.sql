WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON
DECLARE
  n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') IN ('SYS', 'SYSTEM') OR
     SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> SYS_CONTEXT('USERENV', 'SESSION_USER') THEN
    RAISE_APPLICATION_ERROR(-20110, 'Connect as a dedicated empty installation user; do not alter CURRENT_SCHEMA.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS;
  IF n <> 0 THEN
    RAISE_APPLICATION_ERROR(-20111, 'Installation schema must be empty. Existing schemas require a reviewed migration.');
  END IF;
  SELECT COUNT(*) INTO n FROM NLS_DATABASE_PARAMETERS
    WHERE (PARAMETER='NLS_CHARACTERSET' AND VALUE='AL32UTF8')
       OR (PARAMETER='NLS_NCHAR_CHARACTERSET' AND VALUE='AL16UTF16');
  IF n <> 2 THEN
    RAISE_APPLICATION_ERROR(-20112, 'Database character sets differ from captured production.');
  END IF;
END;
/
